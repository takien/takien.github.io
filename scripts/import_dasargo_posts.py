def slugify(s):
    s = s.lower().strip()
    s = re.sub(r"[^\w\s-]", "", s)
    s = re.sub(r"[\s_-]+", "-", s)
    return s.strip("-")

out_dir = "src/content/posts"
os.makedirs(out_dir, exist_ok=True)

created_files = []
for p in posts_data:
    dt = datetime.fromisoformat(p["date_str"].replace("Z", "+00:00"))
    y_str = dt.strftime("%Y")
    m_str = dt.strftime("%m")
    d_str = dt.strftime("%d")
    
    slug_part = slugify(p["title"])
    if not slug_part or len(slug_part) < 3:
        slug_part = f"post-{dt.strftime('%H%M')}"
        
    full_slug = f"{y_str}/{m_str}/{d_str}/{slug_part}"
    filename = f"dasargo_{y_str}_{m_str}_{d_str}_{slug_part}.md"
    filepath = os.path.join(out_dir, filename)
    
    # Format tags
    tags_yaml = ", ".join([f'"{t}"' for t in p["tags"] + ["dasargo.blog.com"]])
    
    # Format comments
    comments_yaml = ""
    if p["comments"]:
        comments_yaml = "comments:\n"
        for c in p["comments"]:
            text_indented = c['text'].replace('\n', '\n      ')
            comments_yaml += f"""  - author: "{c['author']}"
    date: "{c['date']}"
    text: "{text_indented}"\n"""
    else:
        comments_yaml = "comments: []\n"
        
    md_content = f"""---
title: "{p['title']}"
date: "{p['date_str']}"
categories: ["Pribadi"]
tags: [{tags_yaml}]
slug: "{full_slug}"
legacyUrl: "/{full_slug}/"
source: "dasargo.blog.com"
{comments_yaml.strip()}
---

{p['content']}
"""
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(md_content)
    created_files.append((filename, p['title'], p['date_str']))

print(f"Successfully generated {len(created_files)} posts.")
for fn, t, d in sorted(created_files, key=lambda x: x[2]):
    print(f"[{d}] {fn} -> {t[:40]}")
