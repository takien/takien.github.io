for p in posts_data:
    filepath = os.path.join(out_dir, p["filename"])
    tags_yaml = ", ".join([f'"{t}"' for t in p["tags"]])
    
    comments_yaml = ""
    if p["comments"]:
        comments_yaml = "comments:\n"
        for c in p["comments"]:
            text_indented = c['text'].replace('\n', '\n      ')
            comments_yaml += f"""  - author: "{c['author']}"
    date: "{c['date']}"
    text: "{text_indented}"\n"""
    else:
        comments_yaml = "comments: []\n"
        
    md_content = f"""---
title: "{p['title']}"
date: "{p['date_str']}"
categories: ["Pribadi"]
tags: [{tags_yaml}]
slug: "{p['slug']}"
legacyUrl: "/{p['slug']}/"
source: "dasargo.blog.com"
{comments_yaml.strip()}
---

{p['content']}
"""
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(md_content)
